// Draws the app's custom symbols as SF Symbols templates.
//
//   swift Design/symbols.swift                # regenerate the symbols in place
//   swift Design/symbols.swift <preview.svg>  # and a plain SVG to look at
//
// One so far: `berry`, the mark beside a Raspberry Pi in the host list. SF
// Symbols has an Apple logo and nothing for a Pi.
//
// **It is a picture of the fruit, and deliberately not the Raspberry Pi logo
// or anything close to it.** Their trademark rules (read 1 Oct 2026, last
// updated 17 June 2026) allow the logo only "in connection with the sale or
// distribution of genuine Raspberry Pi products or services", require a
// licence for commercial use, and separately forbid "a name or logo which is
// so similar to the Raspberry Pi Marks that it may confuse or mislead". So a
// near-copy is no safer than the original. The logo is one outline cut into
// segments under two broad leaves; this is loose round drupelets under a
// five-pointed calyx and a stem. Keep it that way: do not redraw it towards
// the logo.
//
// Run it, never edit the SVG. The template needs each shape as a filled path
// at fixed coordinates under fixed layer names, which is not something to
// keep right by hand.

import Foundation

func fail(_ message: String) -> Never {
    FileHandle.standardError.write(Data("symbols: \(message)\n".utf8))
    exit(1)
}

func number(_ value: Double) -> String { String(format: "%.2f", value) }

/// A circle as four cubic curves: the template's importer is only known to
/// take the commands the SF Symbols app itself exports, and arcs are not
/// among them.
func circle(_ cx: Double, _ cy: Double, _ r: Double) -> String {
    let k = r * 0.5522847498
    let p = { (x: Double, y: Double) in "\(number(cx + x)) \(number(cy + y))" }
    return "M\(p(r, 0))"
        + "C\(p(r, k)) \(p(k, r)) \(p(0, r))"
        + "C\(p(-k, r)) \(p(-r, k)) \(p(-r, 0))"
        + "C\(p(-r, -k)) \(p(-k, -r)) \(p(0, -r))"
        + "C\(p(k, -r)) \(p(r, -k)) \(p(r, 0))Z"
}

func polygon(_ points: [(Double, Double)]) -> String {
    "M" + points.map { "\(number($0.0)) \(number($0.1))" }.joined(separator: "L") + "Z"
}

/// The berry, in template units: x from 0 to `width`, the baseline at y 0 and
/// up negative. The cap height is 70.46, and a symbol sits centred on the
/// middle of it — so this runs from about 8 below the baseline to 88 above.
let width = 86.0
let berry: [String] = {
    let centre = width / 2
    let radius = 9.7, across = 21.6, down = 18.2
    var paths: [String] = []
    // Drupelets, packed like a honeycomb: broad at the shoulder and blunt at
    // the foot. Tapered to a single one it reads as a bunch of grapes.
    for (row, count) in [3, 4, 3, 2].enumerated() {
        let y = -54.0 + Double(row) * down
        for index in 0..<count {
            let x = centre + (Double(index) - Double(count - 1) / 2) * across
            paths.append(circle(x, y, radius))
        }
    }
    // The calyx: five sepals fanned over the shoulder.
    paths.append(polygon([
        (centre, -79),
        (centre - 8, -72.5), (centre - 20, -80), (centre - 17, -70.5), (centre - 31, -68.5),
        (centre - 15, -63.5), (centre, -66.5), (centre + 15, -63.5),
        (centre + 31, -68.5), (centre + 17, -70.5), (centre + 20, -80), (centre + 8, -72.5),
    ]))
    // And the stem, leaning.
    paths.append(polygon([
        (centre - 3, -76), (centre + 0.5, -88), (centre + 6.5, -86.4), (centre + 3.2, -75),
    ]))
    return paths
}()

/// The template: a 3300 × 2200 sheet whose layer and guide names are what
/// Xcode reads. Only Regular-M is drawn; the other weights and scales are
/// derived from it.
func template(_ paths: [String], width: Double) -> String {
    let left = 1400.0, baseline = 1126.0
    let drawn = paths.map { "   <path d=\"\($0)\"/>" }.joined(separator: "\n")
    return """
    <?xml version="1.0" encoding="UTF-8"?>
    <!--Generated by Design/symbols.swift. Do not edit.-->
    <svg version="1.1" xmlns="http://www.w3.org/2000/svg" xmlns:xlink="http://www.w3.org/1999/xlink" width="3300" height="2200">
     <g id="Notes">
      <rect height="2200" id="artboard" style="fill:white;opacity:1" width="3300" x="0" y="0"/>
      <text id="template-version" style="fill:#505050;font-family:-apple-system;font-size:13;text-anchor:end" transform="matrix(1 0 0 1 3036 1933)">Template v.3.0</text>
     </g>
     <g id="Guides">
      <line id="Baseline-S" style="fill:none;stroke:#27AAE1;opacity:1;stroke-width:0.5" x1="263" x2="3036" y1="696" y2="696"/>
      <line id="Capline-S" style="fill:none;stroke:#27AAE1;opacity:1;stroke-width:0.5" x1="263" x2="3036" y1="625.541" y2="625.541"/>
      <line id="Baseline-M" style="fill:none;stroke:#27AAE1;opacity:1;stroke-width:0.5" x1="263" x2="3036" y1="1126" y2="1126"/>
      <line id="Capline-M" style="fill:none;stroke:#27AAE1;opacity:1;stroke-width:0.5" x1="263" x2="3036" y1="1055.54" y2="1055.54"/>
      <line id="Baseline-L" style="fill:none;stroke:#27AAE1;opacity:1;stroke-width:0.5" x1="263" x2="3036" y1="1556" y2="1556"/>
      <line id="Capline-L" style="fill:none;stroke:#27AAE1;opacity:1;stroke-width:0.5" x1="263" x2="3036" y1="1485.54" y2="1485.54"/>
      <line id="left-margin-Regular-M" style="fill:none;stroke:#00AEEF;stroke-width:0.5;opacity:1.0" x1="\(number(left))" x2="\(number(left))" y1="1030.79" y2="1150.12"/>
      <line id="right-margin-Regular-M" style="fill:none;stroke:#00AEEF;stroke-width:0.5;opacity:1.0" x1="\(number(left + width))" x2="\(number(left + width))" y1="1030.79" y2="1150.12"/>
     </g>
     <g id="Symbols">
      <g id="Regular-M" transform="matrix(1 0 0 1 \(number(left)) \(number(baseline)))">
    \(drawn)
      </g>
     </g>
    </svg>

    """
}

let design = URL(fileURLWithPath: #filePath).deletingLastPathComponent()
let symbols = design.deletingLastPathComponent()
    .appendingPathComponent("BleatKit/Sources/BleatUI/Resources/Symbols.xcassets")

func write(_ name: String, _ paths: [String], width: Double) {
    let set = symbols.appendingPathComponent("\(name).symbolset")
    do {
        try FileManager.default.createDirectory(at: set, withIntermediateDirectories: true)
        try template(paths, width: width)
            .write(to: set.appendingPathComponent("\(name).svg"), atomically: true, encoding: .utf8)
        let contents = """
        {
          "info" : { "author" : "xcode", "version" : 1 },
          "symbols" : [ { "filename" : "\(name).svg", "idiom" : "universal" } ]
        }

        """
        try contents.write(to: set.appendingPathComponent("Contents.json"), atomically: true, encoding: .utf8)
    } catch {
        fail("could not write \(name): \(error)")
    }
}

write("berry", berry, width: width)

if CommandLine.arguments.count > 1 {
    let drawn = berry.map { "<path d=\"\($0)\"/>" }.joined()
    let preview = """
    <svg xmlns="http://www.w3.org/2000/svg" viewBox="\(number(width / 2 - 60)) -100 120 120" width="600" height="600">\
    <rect x="\(number(width / 2 - 60))" y="-100" width="120" height="120" fill="white"/>\(drawn)</svg>
    """
    do {
        try preview.write(toFile: CommandLine.arguments[1], atomically: true, encoding: .utf8)
    } catch {
        fail("could not write the preview: \(error)")
    }
}
